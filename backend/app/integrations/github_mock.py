from app.core.logger import get_logger

logger = get_logger("github_mock")


class GitHubMock:
    """Simulates GitHub REST API v3 interactions."""

    ORG = "intenta-org"

    async def create_repository(self, session_id: str, goal: str) -> dict:
        await asyncio.sleep(0.05)
        repo_name = f"intenta-{session_id[:8]}"

        result = {
            "integration": "GitHub",
            "action": "create_repository",
            "full_name": f"{self.ORG}/{repo_name}",
            "description": f"Auto-generated by INTENTA: {goal[:150]}",
            "visibility": "private",
            "default_branch": "main",
            "topics": ["intenta", "auto-generated", "enterprise"],
            "has_issues": True,
            "has_wiki": True,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "clone_url": f"https://github.com/{self.ORG}/{repo_name}.git",
            "ci_workflow": "github-actions/ci.yml created",
        }

        logger.info("github_repo_created", repo=repo_name)
        return result

